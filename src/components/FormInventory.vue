<script setup>
import axios from 'axios'
import { defineProps, defineEmits } from 'vue'
import { ref, onMounted, computed } from 'vue'
import { useSuppliersStore } from '@/stores/suppliers'
import { useUnitlistsStore } from '@/stores/unitlist'
import { useAuthStore } from '@/stores/auth'
import { useCategoriesStore } from '@/stores/categories'
import useNotification from '@/service/notificationService'
import { RiLockFill, RiCloseCircleFill, RiSave3Fill } from '@remixicon/vue'

const props = defineProps({
  inventory: {
    type: Object,
    default: null
  },
  mode: {
    type: String,
    default: 'entry' // 'entry', 'edit', or 'view'
  }
})

const siteurl = import.meta.env.VITE_API_URL
const { notify } = useNotification()
const suppliersStore = useSuppliersStore()
const categoryStore = useCategoriesStore()
const unitlistStore = useUnitlistsStore()
const authStore = useAuthStore()
const csrfToken = document.querySelector('meta[name="csrf-token"]').getAttribute('content')

const form = ref({
  item_list: props.inventory ? props.inventory.item_list : '',
  description: props.inventory ? props.inventory.description : '',
  qty: props.inventory ? props.inventory.qty : '0',
  unit: props.inventory ? props.inventory.unit : '',
  category: props.inventory ? props.inventory.category : '',
  supplier_id: props.inventory ? props.inventory.supplier_id : '',
  s_name: props.inventory ? props.inventory.s_name : ''
})

const searchCategoryText = ref('')
const showCategoryList = ref(false)

const searchSupplierText = ref('')
const showSupplierList = ref(false)

const searchUnitText = ref('')
const showUnitList = ref(false)

onMounted(async () => {
  await suppliersStore.fetchSuppliers()
  await categoryStore.fetchCategories()
  await unitlistStore.fetchUnitlists()

  if (props.inventory) {
    searchCategoryText.value = props.inventory.category
    searchUnitText.value = props.inventory.unit
    searchSupplierText.value = props.inventory.s_name
  }
})

const handleCategorySearch = () => {
  showCategoryList.value = true
}

const handleCategoryBlur = () => {
  setTimeout(() => {
    showCategoryList.value = false
  }, 200)
}

const selectCategory = (category) => {
  form.value.category = category.description
  searchCategoryText.value = category.description
  showCategoryList.value = false
}

const filteredCategory = computed(() => {
  if (!categoryStore.categories) return []
  const search = searchCategoryText.value.toLowerCase()
  return categoryStore.categories.filter((category) =>
    category.description.toLowerCase().includes(search)
  )
})

const handleSupplierSearch = () => {
  showSupplierList.value = true
}

const handleSupplierBlur = () => {
  setTimeout(() => {
    showSupplierList.value = false
  }, 200)
}

const selectSupplier = (supplier) => {
  form.value.supplier_id = supplier.id
  searchSupplierText.value = supplier.s_name
  showSupplierList.value = false
}

const filteredSuppliers = computed(() => {
  if (!suppliersStore.suppliers) return []
  const search = searchSupplierText.value.toLowerCase()
  return suppliersStore.suppliers.filter((supplier) =>
    supplier.s_name.toLowerCase().includes(search)
  )
})

const handleUnitlistSearch = () => {
  showUnitList.value = true
}

const handleUnitlistBlur = () => {
  setTimeout(() => {
    showUnitList.value = false
  }, 200)
}

const selectUnitlist = (unit) => {
  form.value.unit = unit.unit
  searchUnitText.value = unit.unit
  showUnitList.value = false
}

const filteredUnitlists = computed(() => {
  if (!unitlistStore.unitlists) return []
  const search = searchUnitText.value.toLowerCase()
  return unitlistStore.unitlists.filter((unit) => unit.unit.toLowerCase().includes(search))
})

const emit = defineEmits(['close', 'refresh'])
const closeModal = () => {
  emit('close')
}

const submitForm = async () => {
  try {
    const headers = {
      'Content-Type': 'application/json',
      Accept: 'application/json',
      Authorization: authStore.token,
      'X-CSRF-TOKEN': csrfToken
    }

    let response

    if (props.inventory) {
      response = await axios.put(
        `${siteurl}/api/inventory/update?code=${props.inventory.item_list}`,
        form.value,
        {
          headers
        }
      )
    } else {
      response = await axios.post(`${siteurl}/api/inventory/save`, form.value, { headers })
    }

    if (response.status >= 200 && response.status < 300) {
      notify(response.data.message || 'Purchase saved successfully', 'success')
      emit('refresh')
      emit('close')
    } else {
      notify(response.data.message || 'Failed to save purchase', 'error')
    }
  } catch (error) {
    console.error('Error:', error)
    notify(error.response?.data?.message || 'An error occurred while saving purchase', 'error')
  }
}
</script>

