<template>
  <div class="modal">
    <div class="header">
      <span class="close" @click="closeModal">&times;</span>
      <h2 class="heading">
        Item {{ mode === 'edit' ? 'Edit' : mode === 'view' ? 'View' : 'Entry' }} Form
      </h2>
      <div class="modal-content">
        <form @submit.prevent="submitForm" v-if="mode !== 'view'">
          <div class="form-group">
            <label for="item_list">Code:</label>
            <input
              id="item_list"
              v-model="form.item_list"
              type="text"
              required
              readonly
              :placeholder="form.item_list ? '' : 'Code will be generated by the system.'"
            />
            <RiLockFill class="lock-icon" />
          </div>
          <div class="form-group">
            <label for="material_desc">Description:</label>
            <textarea
              id="material_desc"
              v-model="form.description"
              :readonly="mode === 'view'"
              required
            ></textarea>
          </div>
          <div class="form-group">
            <label for="qty">Qty:</label>
            <input id="qty" v-model="form.qty" type="number" value="0" required readonly />
            <RiLockFill class="lock-icon" />
          </div>
          <div class="form-group">
            <label for="unit">Unit:</label>
            <div class="autocomplete">
              <input
                id="unit"
                v-model="searchUnitText"
                type="text"
                @input="handleUnitlistSearch"
                @focus="showUnitList = true"
                @blur="handleUnitlistBlur"
                placeholder="Search or select a Unit"
                required
                :readonly="mode === 'view'"
              />
              <ul v-if="showUnitList && mode !== 'view'" class="category-list">
                <li
                  v-for="unit in filteredUnitlists"
                  :key="unit.unit"
                  @click="selectUnitlist(unit)"
